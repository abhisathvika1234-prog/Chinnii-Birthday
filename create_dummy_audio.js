const fs = require('fs');
const path = require('path');

// Minimal valid 1-frame silent MP3 byte header
const silentMp3Bytes = Buffer.from([
  0xFF, 0xFB, 0x90, 0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
]);

const musicDir = path.join(__dirname, 'music');
if (!fs.existsSync(musicDir)) {
  fs.mkdirSync(musicDir, { recursive: true });
}

fs.writeFileSync(path.join(musicDir, 'main-song.mp3'), silentMp3Bytes);
fs.writeFileSync(path.join(musicDir, 'letter-song.mp3'), silentMp3Bytes);

console.log('Dummy MP3 files created successfully in music/');
